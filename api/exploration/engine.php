// === EFFECT HELPER ===
function eff($c = null, $e = null, $d = null, $dp = null, $h = null, $hp = null, $ic = null) {
  return function($l) use ($c, $e, $d, $dp, $h, $hp, $ic) {
    $r = [];
    if ($c !== null) $r['chips'] = is_callable($c) ? $c($l) : $c;
    if ($e !== null) $r['exp'] = is_callable($e) ? $e($l) : $e;
    if ($d !== null) $r['damage'] = is_callable($d) ? $d($l) : $d;
    if ($dp !== null) $r['damagePercent'] = $dp;
    if ($h !== null) $r['heal'] = is_callable($h) ? $h($l) : $h;
    if ($hp !== null) $r['healPercent'] = $hp;
    if ($ic !== null) $r['itemCount'] = $ic;
    return $r;
  };
}

// === OUTCOME BUILDER ===
function branchOutcome($text, $weight, $fx, $rc, $rt, $nrt, $rfx = null, $nrfx = null) {
  return ['text' => $text, 'weight' => $weight, 'effects' => $fx,
    'resourceCost' => $rc, 'resourceText' => $rt, 'noResourceText' => $nrt,
    'resourceEffects' => $rfx, 'noResourceEffects' => $nrfx];
}
function branchSection($texts, $fx, $rc, $rts, $nrts, $rfxs = null, $nrfxs = null) {
  $out = [];
  for ($i = 0; $i < 5; $i++) {
    $w = $i < 4 ? 20 : 15;
    $out[] = branchOutcome($texts[$i], $w, $fx[$i]??null, $rc[$i], $rts[$i]??'', $nrts[$i]??'', $rfxs[$i]??null, $nrfxs[$i]??null);
  }
  return $out;
}
