function mkBranch(&$r, &$texts, &$fx_out, &$fx_weights) {
  $out = [];
  for ($i = 0; $i < 5; $i++) {
    $w = $i < 4 ? 20 : 15;
    $ri = $i % 5;
    $out[] = [
      'text' => $texts[$i],
      'weight' => $w,
      'effects' => $fx_out[$i] ?? eff(),
      'resourceCost' => $GLOBALS['RES_NAMES'][$ri],
      'resourceText' => $r['resTexts'][$i] ?? '',
      'noResourceText' => $r['noResTexts'][$i] ?? '',
      'resourceEffects' => $r['resFx'][$i] ?? null,
      'noResourceEffects' => $r['noResFx'][$i] ?? null,
    ];
  }
  return $out;
}

