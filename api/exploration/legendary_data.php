/** Русские названия редкости ключа: 1..7 — лестница качества предметов. */
const LEGENDARY_KEY_TIERS = ['Обычный', 'Редкий', 'Раритетный', 'Эпический', 'Смертоносный', 'Легендарный', 'Божественный'];

/** Формула опыта легендарного финала (масштаб уровня). */
function computeLegendaryReward($formula, $level) {
  $result = [];
  if (isset($formula['chips_lc'])) $result['chips'] = rand(5, 15) + ($level - 1) * 5;
  if (isset($formula['chips_c'])) $result['chips'] = rand(1, 5) + ($level - 1) * 2;
  if (isset($formula['exp_le'])) $result['exp'] = rand(5, 20) + ($level - 1) * 15;
  if (isset($formula['heal_pct'])) $result['healPercent'] = $formula['heal_pct'];
  if (isset($formula['item_count'])) $result['itemCount'] = $formula['item_count'];
  return $result;
}
